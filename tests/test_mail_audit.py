class TestCli(unittest.TestCase):
    def test_fail_on_gates(self):
        # dnone.test: p=none is MEDIUM -> fails the default gate; with --fail-on high only HIGH counts
        base = ("--resolver", RESOLVER)
        self.assertEqual(run(*base, "softfail.test").returncode, 1)          # no DMARC = HIGH
        self.assertEqual(run(*base, "good.test").returncode, 0)
        self.assertEqual(run(*base, "--fail-on", "low", "good.test").returncode, 0)
        p = run(*base, "--fail-on", "never", "nothing.test")
        self.assertEqual(p.returncode, 0)
        self.assertEqual(run(*base, "--fail-on", "high", "dnone.test").returncode, 1)  # no SPF = HIGH
        self.assertEqual(run(*base, "--fail-on", "bogus", "good.test").returncode, 2)

