def chunks(s, n=250):
    return ",".join('"%s"' % s[i:i + n] for i in range(0, len(s), n))


def rsa_key(bits):
    """base64 SubjectPublicKeyInfo of a fresh RSA key, made by the openssl CLI."""
    key = os.path.join(TMP, "k%d.pem" % bits)
    subprocess.run(["openssl", "genpkey", "-algorithm", "RSA", "-pkeyopt", "rsa_keygen_bits:%d" % bits, "-out", key],
                   check=True, capture_output=True)
    der = subprocess.run(["openssl", "pkey", "-in", key, "-pubout", "-outform", "DER"], check=True,
                         capture_output=True).stdout
    return base64.b64encode(der).decode()


