    def spf(self, domain):
        return audit(domain)[1]["spf"]

    def test_good_domain_counts(self):
        s = self.spf("good.test")
        self.assertEqual((s["lookups"], s["void_lookups"]), (1, 0))
        self.assertEqual(s["tree"]["children"][0]["domain"], "_spf.good.test")

    def test_over_the_limit_is_high(self):
        s = self.spf("overlimit.test")
        self.assertEqual(s["lookups"], 11)
        self.assertTrue(any(f["severity"] == "HIGH" and "needs 11 DNS lookups" in f["message"]
                            and "RFC 7208 allows 10" in f["message"] for f in s["findings"]), s["findings"])

    def test_nested_includes_are_counted_across_the_tree(self):
        s = self.spf("nested.test")
        # n1 (1) + [n2, n3, a:] (3) + 4 includes under n2 + 4 under n3 = 12
        self.assertEqual(s["lookups"], 12)
        self.assertTrue(any("needs 12 DNS lookups" in m for m in s["issues"]), s["issues"])
        self.assertEqual([c["domain"] for c in s["tree"]["children"][0]["children"]], ["n2.spf.test", "n3.spf.test"])

    def test_near_the_limit_is_low(self):
        s = self.spf("atlimit.test")
        self.assertEqual(s["lookups"], 9)
        self.assertIn(("LOW", "SPF needs 9 of the 10 allowed DNS lookups -- one more include breaks it"),
                      [(f["severity"], f["message"]) for f in s["findings"]])

    def test_void_lookups(self):
        s = self.spf("void.test")
        self.assertEqual((s["lookups"], s["void_lookups"]), (3, 3))
        self.assertTrue(any("3 void lookups" in m for m in s["issues"]), s["issues"])

    def test_include_without_spf_record_and_loops(self):
        self.assertTrue(any("include:missing.spf.test has no SPF record" in m for m in self.spf("badinclude.test")["issues"]))
        self.assertTrue(any("SPF include loop: loop.test" in m for m in self.spf("loop.test")["issues"]))
        dup = self.spf("dupinclude.test")
        self.assertEqual(dup["lookups"], 3)
        self.assertFalse(any("loop" in m for m in dup["issues"]), dup["issues"])
        self.assertTrue(any("included more than once" in f["message"] and f["severity"] == "INFO" for f in dup["findings"]))

    def test_ptr_mx_limit_and_macros(self):
        self.assertTrue(any("'ptr' mechanism" in m for m in self.spf("ptr.test")["issues"]))
        self.assertTrue(any("has 11 MX hosts" in m for m in self.spf("mxmany.test")["issues"]))
        m = self.spf("macro.test")
        self.assertEqual(m["lookups"], 1)
        self.assertTrue(any("uses a macro" in f["message"] and f["severity"] == "INFO" for f in m["findings"]))

    def test_redirect_counts_a_lookup(self):
        self.assertEqual(self.spf("redirect.test")["lookups"], 1)


