class HttpsHandler(BaseHTTPRequestHandler):
    def log_message(self, *a):
        pass

    def do_GET(self):
        host = (self.headers.get("Host") or "").split(":")[0]
        body = HTTP_ROUTES.get((host, self.path))
        data = (body or "not found").encode()
        self.send_response(200 if body else 404)
        self.send_header("Content-Type", "text/plain")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)


class SmtpServer(threading.Thread):
    """Minimal SMTP listener: greeting, EHLO (optionally advertising STARTTLS), STARTTLS -> TLS."""

    def __init__(self, ctx, starttls=True):
        super().__init__(daemon=True)
        self.ctx, self.starttls = ctx, starttls
        self.sock = socket.socket()
        self.sock.bind(("127.0.0.1", 0))
        self.sock.listen(8)
        self.port = self.sock.getsockname()[1]

    def run(self):
        while True:
            try:
                conn, _ = self.sock.accept()
            except OSError:
                return
            threading.Thread(target=self.session, args=(conn,), daemon=True).start()

    def session(self, conn):
        try:
            conn.settimeout(10)
            conn.sendall(b"220 mx.smtp.test ESMTP test\r\n")
            f = conn.makefile("rb")
            while True:
                line = f.readline().strip().upper()
                if not line:
                    return
                if line.startswith(b"EHLO"):
                    caps = [b"mx.smtp.test", b"PIPELINING", b"8BITMIME"] + ([b"STARTTLS"] if self.starttls else [])
                    conn.sendall(b"".join(b"250-" + c + b"\r\n" for c in caps[:-1]) + b"250 " + caps[-1] + b"\r\n")
                elif line == b"STARTTLS":
                    conn.sendall(b"220 2.0.0 go ahead\r\n")
                    tls = self.ctx.wrap_socket(conn, server_side=True)
                    tls.recv(1024)
                    return
                else:
                    conn.sendall(b"221 bye\r\n")
                    return
        except (OSError, ssl.SSLError):
            pass
        finally:
            conn.close()


def free_dns_port():
    """A port on 127.0.0.1 free right now for both UDP and TCP (dnsmasq binds both).

    Never a fixed port: mutation testing runs this module in several processes at once (mutmut
    --max-children). With a fixed port the second dnsmasq could not bind and that process's tests
    queried the FIRST process's dnsmasq - another corpus (other DKIM keys) that could be torn down
    mid-test - so mutants were killed or kept at random instead of by what the tool does."""
    for _ in range(50):
        u = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        t = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        try:
            u.bind(("127.0.0.1", 0))
            port = u.getsockname()[1]
            t.bind(("127.0.0.1", port))
            return port
        except OSError:
            continue
        finally:
            u.close()
            t.close()
    raise RuntimeError("no free UDP+TCP port on 127.0.0.1")


def dnsmasq_lost_bind(proc, logpath):
    """True when our dnsmasq exited because a parallel run took its port first (try another)."""
    if proc.poll() is None:
        return False
    with open(logpath) as f:
        log = f.read()
    if "Address already in use" in log or "address in use" in log.lower():
        return True
    raise RuntimeError("dnsmasq exited with %s:\n%s" % (proc.returncode, log))


def setUpModule():
    global DNSMASQ, TMP, CERT, HTTPS, SMTP_OK, SMTP_PLAIN, PORT, RESOLVER
    TMP = tempfile.mkdtemp()
    CERT, key = os.path.join(TMP, "cert.pem"), os.path.join(TMP, "key.pem")
    san = ",".join("DNS:" + h for h in HTTPS_HOSTS)
    subprocess.run(["openssl", "req", "-x509", "-newkey", "rsa:2048", "-nodes", "-keyout", key, "-out", CERT,
                    "-days", "2", "-subj", "/CN=mta-sts.good.test", "-addext", "subjectAltName=" + san],
                   check=True, capture_output=True)
    ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    ctx.load_cert_chain(CERT, key)
    HTTPS = HTTPServer(("127.0.0.1", 0), HttpsHandler)
    HTTPS.socket = ctx.wrap_socket(HTTPS.socket, server_side=True)
    threading.Thread(target=HTTPS.serve_forever, daemon=True).start()
    SMTP_OK, SMTP_PLAIN = SmtpServer(ctx), SmtpServer(ctx, starttls=False)
    SMTP_OK.start()
    SMTP_PLAIN.start()

    conf = os.path.join(TMP, "dnsmasq.conf")
    logpath = os.path.join(TMP, "dnsmasq.log")
    binary = shutil.which("dnsmasq") or "/usr/sbin/dnsmasq"
    p = None
    for _ in range(10):
        PORT = free_dns_port()
        RESOLVER = f"127.0.0.1:{PORT}"
        with open(conf, "w") as f:
            f.write("\n".join([f"port={PORT}", "listen-address=127.0.0.1", "bind-interfaces", "no-resolv",
                               "no-hosts", "local=/test/", "edns-packet-max=512"] + records()) + "\n")
        log = open(logpath, "w")  # a pipe would fill up and stall dnsmasq
        DNSMASQ = subprocess.Popen([binary, "-k", f"--conf-file={conf}"], stdout=log, stderr=subprocess.STDOUT)
        for _ in range(50):
            if dnsmasq_lost_bind(DNSMASQ, logpath):
                break
            p = run("--resolver", RESOLVER, "--json", "good.test")
            if p.returncode == 0 and json.loads(p.stdout)[0]["spf"]["present"]:
                # answered: only OUR dnsmasq can hold the port if it is still alive
                time.sleep(0.2)
                if not dnsmasq_lost_bind(DNSMASQ, logpath):
                    return
                break
            time.sleep(0.1)
        else:
            with open(logpath) as f:
                raise RuntimeError("dnsmasq did not come up:\n" + f.read() + "\n" + (p.stdout + p.stderr if p else ""))
    raise RuntimeError("dnsmasq could not bind a port in 10 attempts")


def tearDownModule():
    DNSMASQ.terminate()
    DNSMASQ.wait(5)
    HTTPS.shutdown()
    shutil.rmtree(TMP, ignore_errors=True)


def run(*args):
    env = dict(os.environ, SSL_CERT_FILE=CERT)
    return subprocess.run([sys.executable, TOOL, "--https-port", str(HTTPS.server_address[1])] + list(args),
                          capture_output=True, text=True, timeout=180, env=env)


def audit(domain, *extra):
    p = run("--resolver", RESOLVER, "--json", *extra, domain)
    assert p.returncode in (0, 1), p.stderr
    res = json.loads(p.stdout)
    return p.returncode, res[0]


def findings(r, check=None):
    return [(f["severity"], f["message"]) for f in r["findings"] if check is None or f["check"] == check]


